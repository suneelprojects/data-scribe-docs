CREATE POLICY "Public can read published and due scheduled articles"
ON public.content_articles
FOR SELECT
TO anon, authenticated
USING (
  status = 'published'
  OR (status = 'scheduled' AND scheduled_at IS NOT NULL AND scheduled_at <= now())
);

